import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../..')
const schemaPath = path.join(root, 'apps/backend/.adonisjs/client/registry/schema.d.ts')
const stubPath = path.join(root, 'apps/frontend/types/tuyau-module-stub.ts')

if (!fs.existsSync(schemaPath)) process.exit(0)

const source = fs.readFileSync(schemaPath, 'utf8')
const stripped = source.replace(/^\/\/\/ <reference path="\.\.\/manifest\.d\.ts" \/>\r?\n/m, '')
if (stripped !== source) fs.writeFileSync(schemaPath, stripped)

const names = new Set()
for (const match of stripped.matchAll(/import\('#validators\/[^']+'\)\.([A-Za-z0-9_]+)/g)) {
  names.add(match[1])
}

const stub = [
  '/**',
  ' * Stand-in for #controllers/* and #validators/* so frontend tsc does not load the backend.',
  ' * Call-site types remain the ones exported from lib/api.ts.',
  ' * Regenerated by scripts/prepare-tuyau-types.mjs.',
  ' */',
  "import type { ITYPE } from '../../backend/node_modules/@vinejs/vine/build/src/symbols.js'",
  '',
  'type AnyMethod = (...args: any[]) => any',
  'interface EmptyInput {}',
  'type LooseValidator = { [ITYPE]: EmptyInput }',
  '',
  'const controller: { readonly [method: string]: AnyMethod } = {}',
  'export default controller',
  '',
  ...[...names].map((name) => `export const ${name}: LooseValidator = {} as LooseValidator`),
  '',
].join('\n')

fs.writeFileSync(stubPath, stub)
